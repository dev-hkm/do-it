    private val resIdCache = ConcurrentHashMap<String, Int>()

    @DrawableRes
    fun getIconResId(context: Context, iconName: String): Int {
        if (iconName.isBlank()) return com.composables.icons.lucide.R.drawable.lucide_ic_tag
        return resIdCache.getOrPut(iconName) {
            val resId = context.resources.getIdentifier(iconName, "drawable", context.packageName)
            if (resId != 0) resId else com.composables.icons.lucide.R.drawable.lucide_ic_tag
        }
    }

    fun getIconsForCategory(categoryId: String, query: String = ""): List<String> {
        val baseList = when (categoryId) {
            "popular" -> popularIcons
            "work" -> workIcons
            "study" -> studyIcons
            "personal" -> personalIcons
            "tech" -> techIcons
            "finance" -> financeIcons
            "health" -> healthIcons
            "media" -> mediaIcons
            "travel" -> travelIcons
            "tools" -> toolsIcons
            else -> allIcons
        }

        if (query.isBlank()) return baseList

        val cleanQuery = query.trim().lowercase().replace(" ", "_")
        return allIcons.filter { icon ->
            val cleanName = icon.removePrefix("lucide_ic_")
            cleanName.contains(cleanQuery)
        }
    }

    fun formatIconDisplayName(iconName: String): String {
        return iconName.removePrefix("lucide_ic_")
            .replace("_", " ")
            .replaceFirstChar { if (it.isLowerCase()) it.titlecase() else it.toString() }
    }
